// Rebuild the golem's native Java geometry/animations and embedded texture.
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const m = JSON.parse(fs.readFileSync(path.join(root, 'localimport/the-cogwork-golem-2025-version.bbmodel')));
const groups = new Map(m.groups.map(g => [g.uuid, g]));
const cubes = new Map(m.elements.map(e => [e.uuid, e]));
const f = n => {assert.ok(Number.isFinite(n)); return Number(n.toFixed(6)) + 'F';};
const coord = p => [-p[0], -p[1], p[2]];
const radians = p => coord(p).map(v => f(v * Math.PI / 180)).join(', ');
const lines = ['        MeshDefinition mesh = new MeshDefinition();', '        PartDefinition root = mesh.getRoot();'];
let count = 0;
function visit(node, parent, origin) {
    if (typeof node === 'string') {
        const e = cubes.get(node);
        assert.ok(e && e.type === 'cube' && e.box_uv);
        const size = e.to.map((v,i) => v-e.from[i]);
        const local = [e.origin[0]-e.to[0], e.origin[1]-e.to[1], e.from[2]-e.origin[2]];
        const offset = coord(e.origin.map((v,i) => v-origin[i]));
        const uv = e.faces.north.uv;
        const u = Math.round(Math.min(uv[0],uv[2])-size[2]), v = Math.round(uv[1]-size[2]);
        lines.push(`        ${parent}.addOrReplaceChild("cube_${count++}", CubeListBuilder.create().texOffs(${u}, ${v})${e.mirror_uv ? '.mirror()' : ''}`);
        lines.push(`                .addBox(${[...local,...size].map(f).join(', ')}), PartPose.offsetAndRotation(${offset.map(f).join(', ')}, ${radians(e.rotation || [0,0,0])}));`);
    } else {
        const g = groups.get(node.uuid);
        assert.ok(g && /^[a-z_]+$/.test(g.name));
        const offset = coord(g.origin.map((v,i) => v-origin[i]));
        if (parent === 'root') offset[1] += 24;
        lines.push(`        PartDefinition ${g.name} = ${parent}.addOrReplaceChild("${g.name}", CubeListBuilder.create(),`);
        lines.push(`                PartPose.offsetAndRotation(${offset.map(f).join(', ')}, ${radians(g.rotation)}));`);
        for (const child of node.children) visit(child,g.name,g.origin);
    }
}
for (const node of m.outliner) visit(node,'root',[0,0,0]);
assert.equal(count,m.elements.length);
const texture = m.textures[0];
lines.push(`        return LayerDefinition.create(mesh, ${texture.uv_width}, ${texture.uv_height});`);
const geometry = `package net.maximlvr.asmpthings.client.model;

import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;

// Generated by tools/import-golem.cjs; edit the original Blockbench project.
public final class GolemGeometry {
    private GolemGeometry() {}
    public static LayerDefinition createBodyLayer() {
${lines.join('\n')}
    }
}
`;
const animLines=[];
for (const a of m.animations.filter(a=>['idle','walk'].includes(a.name))) {
    assert.equal(a.loop,'loop');
    animLines.push(`    public static final AnimationDefinition ${a.name.toUpperCase()} = AnimationDefinition.Builder.withLength(${f(a.length)}).looping()`);
    for (const animator of Object.values(a.animators)) {
        if (!animator.keyframes?.length) continue;
        assert.equal(animator.type,'bone');
        for (const channel of new Set(animator.keyframes.map(k=>k.channel))) {
            const frames=animator.keyframes.filter(k=>k.channel===channel).sort((a,b)=>a.time-b.time);
            const target={rotation:'ROTATION',position:'POSITION',scale:'SCALE'}[channel];
            assert.ok(target);
            animLines.push(`            .addAnimation("${animator.name}", new AnimationChannel(AnimationChannel.Targets.${target},`);
            const frameLines=frames.map(k=>{
                assert.equal(k.data_points.length,1);
                const d=k.data_points[0];
                let values=[Number(d.x),Number(d.y),Number(d.z)];
                let method;
                if(channel==='rotation'){ values=coord(values); method='degreeVec'; }
                else if(channel==='position'){values[0]*=-1; method='posVec';}
                else method='scaleVec';
                assert.ok(['catmullrom','linear'].includes(k.interpolation));
                return `                    new Keyframe(${f(k.time)}, KeyframeAnimations.${method}(${values.map(f).join(', ')}), AnimationChannel.Interpolations.${k.interpolation==='catmullrom'?'CATMULLROM':'LINEAR'})`;
            });
            animLines.push(frameLines.join(',\n')+'))');
        }
    }
    animLines.push('            .build();');
}
const animations=`package net.maximlvr.asmpthings.client.model;

import net.minecraft.client.animation.AnimationDefinition;
import net.minecraft.client.animation.AnimationChannel;
import net.minecraft.client.animation.Keyframe;
import net.minecraft.client.animation.KeyframeAnimations;

// Generated by tools/import-golem.cjs.
public final class GolemAnimations {
    private GolemAnimations() {}
${animLines.join('\n')}
}
`;
const java = path.join(root,'src/main/java/net/maximlvr/asmpthings/client/model');
fs.writeFileSync(path.join(java,'GolemGeometry.java'),geometry);
fs.writeFileSync(path.join(java,'GolemAnimations.java'),animations);
assert.ok(texture.source.startsWith('data:image/png;base64,'));
fs.writeFileSync(path.join(root,'src/main/resources/assets/asmpthingsmod/textures/entity/golem.png'),Buffer.from(texture.source.split(',')[1],'base64'));
console.log(`Golem: ${count} cubes, idle/walk animations, ${texture.uv_width}x${texture.uv_height} texture.`);
